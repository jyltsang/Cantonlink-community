// Generates tools/simplified-chars.mjs: characters that only exist in
// Simplified Chinese, with their Traditional form, so the AI checks can catch
// replies written in Simplified characters (开会 instead of 開會).
// Data: OpenCC via opencc-js (MIT and Apache-2.0). A character counts as
// Simplified-only when OpenCC converts it and it never stays unchanged in a
// Traditional phrase (so 后, 干 and 里, valid in 皇后, 干擾 and 公里, are kept).
//   node tools/gen-simplified.mjs

import { writeFileSync } from 'node:fs';
// The package does not export its dictionaries by name, so load the files.
const dict = (name) => import(new URL(`../node_modules/opencc-js/dist/esm-lib/dict/${name}.js`, import.meta.url)).then((m) => m.default);
const [st, sp, hk] = await Promise.all(['STCharacters', 'STPhrases', 'HKVariants'].map(dict));

// Cantonese characters that OpenCC treats as Simplified forms of Mandarin
// words: 吓 (睇吓, have a look) and 晒 (賣晒, sold out).
const CANTONESE = new Set(['吓', '晒']);

const pairs = (table) => table.split('|').map((entry) => entry.split(' '));
const traditional = new Set();
for (const [, to] of pairs(sp)) for (const c of to) traditional.add(c);
for (const [from, to] of pairs(hk)) for (const c of from + to) traditional.add(c);

const map = [];
for (const [from, to] of pairs(st)) {
  if ([...from].length === 1 && [...to].length === 1 && from !== to && !traditional.has(from) && !CANTONESE.has(from)) map.push(from + to);
}
writeFileSync(new URL('./simplified-chars.mjs', import.meta.url), `// Generated by tools/gen-simplified.mjs from OpenCC data (Apache-2.0); do not edit.
// Each pair is a Simplified-only character followed by its Traditional form.
export const SIMPLIFIED_PAIRS = '${map.join('')}';
`);
console.log(`✓ ${map.length} Simplified-only characters`);
